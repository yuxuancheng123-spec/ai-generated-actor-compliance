#!/usr/bin/env python3
"""Generate web/rules-data.js from rules/rules.json so the static demo uses the backend's rulebook.

Run after editing rules/rules.json:  python3 scripts/build_web_rules.py
tests/test_engine_parity.py fails if the generated file is stale.
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "rules" / "rules.json"
TARGET = ROOT / "web" / "rules-data.js"


def render() -> str:
    rulebook = json.loads(SOURCE.read_text(encoding="utf-8"))
    payload = json.dumps({"version": rulebook["version"], "rules": rulebook["rules"]}, ensure_ascii=False, indent=2)
    return (
        "// Generated by scripts/build_web_rules.py from rules/rules.json. Do not edit by hand.\n"
        "(function (root) {\n"
        f"  const data = {payload};\n"
        "  if (typeof module === \"object\" && module.exports) module.exports = data;\n"
        "  else root.RULES_DATA = data;\n"
        "})(typeof self !== \"undefined\" ? self : this);\n"
    )


if __name__ == "__main__":
    TARGET.write_text(render(), encoding="utf-8")
    print(f"Wrote {TARGET.relative_to(ROOT)}")
